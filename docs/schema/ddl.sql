-- ============================================================================
-- Star Schema DDL — Windows Security Telemetry (Sysmon + Security + PowerShell + WFP)
-- Source: dadosdia1.json / dadosdia2.json (MITRE ATT&CK "dmevals" / APT29 eval, NDJSON)
-- Target: Gold layer of a medallion lakehouse.
-- Platform: ANSI SQL / PostgreSQL-compatible types (portable to Snowflake/Delta/Iceberg
--           with minor type-name substitution — kept generic on purpose, per instructions).
-- Companion doc: docs/schema/star_schema.md (grain, rationale, SCD strategy, ER diagram)
-- Design reference: KB data-modeling/patterns/star-schema.md, concepts/scd-types.md
-- ============================================================================
-- Conventions used throughout:
--   *_sk   = surrogate key (system-generated, stable join key)
--   *_nk   = natural key (business/source identifier)
--   -1     = reserved "Not Applicable / Unknown" member row on every dimension
--            (see docs/schema/star_schema.md §7) — fact FKs are NOT NULL, never bare NULL.
-- ============================================================================


-- ============================================================================
-- DIM_DATE — conformed, Type 0 (static/derived; no SCD; regenerable, never updated in place)
-- Grain: one row per calendar date.
-- Source: derived from UtcTime (canonical event time) date part. Not sourced from a single
--         raw field; generated by a calendar-date generator script covering the observed
--         range (2020-05-01 .. 2020-05-02) plus buffer.
-- ============================================================================
