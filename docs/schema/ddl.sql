-- ============================================================================
-- DIM_PROCESS — conformed, SCD TYPE 2
-- Grain: one row = one known version of one process instance (ProcessGuid).
-- Rationale for Type 2 (not a generic "always version everything" choice): the SAME
-- ProcessGuid is observed incrementally with different attribute completeness across
-- EventIDs (full detail only at EventID 1); a new version row per enriching sighting
-- creates an auditable "what did we know, and when" trail, and surfaces attribute
-- conflicts (e.g. Image path mismatch for the same ProcessGuid) as a security signal
-- instead of silently overwriting them. See docs/schema/star_schema.md §4.5.
--
-- Source-to-target mapping:
--   ProcessGuid                                  -> process_guid (natural key)
--   ProcessId                                    -> process_id (informational only, NOT a key — PIDs are recycled by the OS)
--   Image                                        -> image_path (+ parsed image_name)
--   Hashes ("SHA1=..,MD5=..,SHA256=..,IMPHASH=..") -> hash_sha1, hash_md5, hash_sha256, hash_imphash (parsed)
--   CommandLine                                  -> command_line
--   CurrentDirectory                              -> current_directory
--   IntegrityLevel                                -> integrity_level
--   Company, Product, Description,
--     OriginalFileName, FileVersion               -> company, product, description, original_file_name, file_version
--   ParentProcessGuid, ParentImage,
--     ParentProcessId, ParentCommandLine           -> parent_process_guid, parent_image, parent_process_id, parent_command_line
--   LogonGuid, TerminalSessionId                   -> logon_guid, terminal_session_id
--   (EventID that produced this version)           -> record_source
-- ============================================================================
CREATE TABLE dim_process (
    process_sk          BIGINT        NOT NULL,          -- FIX M5: deterministic hash surrogate = hash(process_guid, effective_from); unique per SCD2 version, MERGE/upsert- & rerun-safe, Iceberg-compatible (no IDENTITY)
    process_guid         VARCHAR(38)   NOT NULL,          -- natural key (not unique alone across SCD2 versions)
    process_id            BIGINT,                          -- PID at time of this version; informational only
    image_path            VARCHAR(500),
    image_name            VARCHAR(260),                    -- derived basename of image_path
    company                VARCHAR(200),
    product                VARCHAR(200),
    description            VARCHAR(500),
    original_file_name     VARCHAR(260),
    file_version            VARCHAR(100),
    command_line             VARCHAR(4000),
    current_directory         VARCHAR(500),
    integrity_level            VARCHAR(20),
    hash_sha1                   CHAR(40),
    hash_md5                     CHAR(32),
    hash_sha256                   CHAR(64),
    hash_imphash                   CHAR(32),
    parent_process_guid              VARCHAR(38),           -- text linkage only; not a hard FK (parent row may not be loaded yet — late-arriving dimension)
    parent_process_id                 BIGINT,
    parent_image                       VARCHAR(500),
    parent_command_line                  VARCHAR(4000),
    logon_guid                            VARCHAR(38),
    terminal_session_id                    VARCHAR(10),
    record_source                           VARCHAR(20) NOT NULL,  -- EventID that produced this version, e.g. '1','10','11'
    effective_from                          TIMESTAMP   NOT NULL,
    effective_to                             TIMESTAMP   NOT NULL DEFAULT TIMESTAMP '9999-12-31 00:00:00',
    is_current                                BOOLEAN    NOT NULL DEFAULT TRUE,
    _loaded_at                                 TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_dim_process PRIMARY KEY (process_sk),
    CONSTRAINT uq_dim_process_guid_version UNIQUE (process_guid, effective_from)
);

-- FIX C2: fact.process_sk MUST be resolved by a POINT-IN-TIME join
--   dim_process.process_guid = <event process_guid>
--   AND <event_utc_time> BETWEEN effective_from AND effective_to
-- (NOT is_current = TRUE — that misattributes historical events to a later, possibly
--  masquerading, Image-path version and defeats the §4.5 conflict-detection rationale).
-- This range index supports that as-of-event-time lookup; the is_current partial index is
-- retained only for the "latest known state" convenience view, never for fact FK resolution.
CREATE INDEX ix_dim_process_pit ON dim_process (process_guid, effective_from, effective_to);
CREATE INDEX ix_dim_process_current ON dim_process (process_guid) WHERE is_current = TRUE;

INSERT INTO dim_process (process_sk, process_guid, record_source, effective_from)
VALUES (-1, 'N/A', 'N/A', TIMESTAMP '1900-01-01 00:00:00');

-- FIX M4: joining fact -> dim_process on the NATURAL key (process_guid) fans out across every
-- SCD2 version and multiplies row counts. Two safe patterns only:
--   1. fact.process_sk = dim_process.process_sk        (exact version at event time; preferred)
--   2. ad-hoc natural-key joins go through this pre-filtered current-version view, never the base table:
CREATE VIEW dim_process_current AS
    SELECT * FROM dim_process WHERE is_current = TRUE;


-- ============================================================================
-- DIM_NETWORK_ENDPOINT — conformed, SCD Type 1, ROLE-PLAYING (source/destination on fact)
-- Grain: one row per unique IP address observed. Sparse fact usage (~0.4-0.6% of rows)
-- but conformed/reused across NetworkConnect (Sysmon EventID 3) and WFP (5156/5158/5447).
-- Deliberately excludes port (kept as degenerate fact column — see doc §4.6: source ports
-- are ephemeral/high-cardinality and don't belong on a dimension).
--
-- Source-to-target mapping:
--   SourceIp / SourceAddress (WFP)               -> ip_address (role: source)
--   DestinationIp / DestAddress (WFP)             -> ip_address (role: destination)
--   SourceIsIpv6 / DestinationIsIpv6              -> is_ipv6
--   SourceHostname / DestinationHostname          -> hostname (always empty in current data; retained for future DNS enrichment)
-- ============================================================================
CREATE TABLE dim_network_endpoint (
    endpoint_sk     BIGINT        NOT NULL,             -- FIX M5: deterministic hash surrogate = hash(ip_address); MERGE/upsert-safe, Iceberg-compatible (no IDENTITY)
    ip_address      VARCHAR(45)   NOT NULL,             -- natural key; VARCHAR(45) covers IPv6 (display form)
    is_ipv6         BOOLEAN       NOT NULL DEFAULT FALSE,
    ip_numeric      NUMERIC(39,0),                       -- FIX M3: numeric IP for CIDR/range scans (IPv4 -> 32-bit int; IPv6 -> 128-bit); populated at load, NULL only for -1 member
    ip_prefix_24    VARCHAR(15),                          -- FIX M3: precomputed /24 (IPv4) for common SOC subnet filters, e.g. '10.0.0'
    hostname        VARCHAR(255),                        -- DNS reverse-resolution, nullable (sparse/empty in current data)
    ip_class        VARCHAR(20),                          -- 'private','public','loopback','link_local' (derived at load time)
    _loaded_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_dim_network_endpoint PRIMARY KEY (endpoint_sk),
    -- FIX L1: NK is ip_address alone (a dotted-quad string is never valid IPv6 notation, so
    -- is_ipv6 is derivable and adds no disambiguation) — DDL and doc now agree on single-column NK.
    CONSTRAINT uq_dim_network_endpoint_ip UNIQUE (ip_address)
);

